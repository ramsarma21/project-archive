// The single import surface onto @pa/curriculum, plus the narrow port this
// package needs from it.
//
// THIS PACKAGE INVENTS NO IDENTIFIER SCHEME. The repository already holds at
// least eight ways of writing the same standard — `8.4(A)`, `8.4A`, `(4)(A)`,
// `8.4(A):STAMP_ACT`, `(4)(A)·Stamp Act`, `8.12`, bare clause ids,
// `BOS.MD01.CONCEPT.*`, `RCC.*`, `RCL.*`, `MICRO.*`, `TEKS.PENDING_SME_REVIEW` —
// and @pa/curriculum exists to collapse them onto one canonical registry with an
// alias table. A ninth invented on the reporting surface would be the worst of
// the set: this is the artifact a district reads, and a mastery row keyed by a
// private identifier is a row nobody can reconcile against the state's standards.
//
// So every standard printed by this package is the registry's canonical `SeCode`,
// and the only other spelling emitted is `formatBareLetter` — `8.4A` — which is
// generated by the registry's own formatter rather than by string surgery here,
// because a district's warehouse writes it that way.
//
// TWO HONESTY RULES CARRIED STRAIGHT THROUGH FROM THE REGISTRY.
//
// 1. A PARAPHRASE IS NEVER RENDERED AS THE STANDARD'S OWN WORDS. Exactly one of
//    Boston's 23 student expectations (8.4(A)) has verbatim cited text; for the
//    other 22 the repository never held it. `descriptionSource` says which one a
//    reader is looking at, on every row, and there is no field that could carry a
//    paraphrase without it. A teacher-facing report that quotes a fabricated
//    standard is a compliance problem, not a cosmetic one.
// 2. THE CONCEPT-TO-STANDARD MAPPING IS DRAFT. Nothing in the Boston seed holds
//    SME_APPROVED, so `reviewStatus` travels with the concept and becomes a claim
//    qualifier rather than being quietly dropped. See claim.ts.

