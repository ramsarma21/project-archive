#!/usr/bin/env node
import crypto from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(here, "../../..");
const contentRoot = join(repositoryRoot, "content/boston/act1");
const output = join(
  repositoryRoot,
  "packages/chapter-boston/src/generated/act1OpenResponseContent.generated.ts",
);

const files = {
  manifest: "package.manifest.json",
  allowlists: "allowlists.json",
  sources: "sources/sources.json",
  items: "prompts/open-response-items.json",
  rubrics: "rubrics/rubrics.json",
  feedback: "feedback/feedback.json",
  classifier: "classifier/classifier-schema.json",
  archiveConnections: "archive/connections.json",
  npcFollowups: "dialogue/npc-followups.json",
};

const documents = {};
const hashes = {};
for (const [key, relativePath] of Object.entries(files)) {
  const raw = readFileSync(join(contentRoot, relativePath), "utf8");
  documents[key] = JSON.parse(raw);
  hashes[key] = `sha256:${crypto.createHash("sha256").update(raw).digest("hex")}`;
}
const packageHash = `sha256:${crypto
  .createHash("sha256")
  .update(
    Object.entries(hashes)
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([key, hash]) => `${key}\u0000${hash}`)
      .join("\u0000"),
  )
  .digest("hex")}`;
const hashRecord = (value) =>
  `sha256:${crypto
    .createHash("sha256")
    .update(JSON.stringify(value))
    .digest("hex")}`;
const recordHashes = {
  sources: Object.fromEntries(
    documents.sources.packets.map((record) => [
      record.packetId,
      hashRecord(record),
    ]),
  ),
  items: Object.fromEntries(
    documents.items.items.map((record) => [record.itemId, hashRecord(record)]),
  ),
  rubrics: Object.fromEntries(
    documents.rubrics.rubrics.map((record) => [
      record.rubricId,
      hashRecord(record),
    ]),
  ),
  feedback: Object.fromEntries(
    documents.feedback.entries.map((record) => [
      record.feedbackId,
      hashRecord(record),
    ]),
  ),
  archiveConnections: Object.fromEntries(
    documents.archiveConnections.cards.map((record) => [
      record.cardId,
      hashRecord(record),
    ]),
  ),
  npcFollowups: Object.fromEntries(
    documents.npcFollowups.followups.map((record) => [
      record.nodeId,
      hashRecord(record),
    ]),
  ),
  classifier: {
    [documents.classifier.classifierSchemaId]: hashRecord(documents.classifier),
  },
};

const source = `/* eslint-disable */
// GENERATED by packages/chapter-boston/scripts/generate-act1-open-response.mjs.
// Do not hand-edit. Source: content/boston/act1/.

export const ACT1_OPEN_RESPONSE_CONTENT_HASHES = ${JSON.stringify(
  { ...hashes, package: packageHash },
  null,
  2,
)} as const;

export const ACT1_OPEN_RESPONSE_RECORD_HASHES = ${JSON.stringify(
  recordHashes,
  null,
  2,
)} as const;

export const ACT1_OPEN_RESPONSE_CONTENT = ${JSON.stringify(
  documents,
  null,
  2,
)} as const;
`;

mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, source);
console.log(
  JSON.stringify({
    generated: "packages/chapter-boston/src/generated/act1OpenResponseContent.generated.ts",
    packageHash,
  }),
);

