// Build-time collision-metadata compiler.
//
// Parses the deployed/optimized GLB set, records content hash + raw local
// bounds + node/mesh/triangle counts, combines that measured data with the
// authored asset-local collision sidecars (assets/source/collision/*), derives
// fitted visual bounds + per-placement audit deltas, and emits generated
// metadata + a human-readable report into assets/build/collision.
//
// It does NOT touch the chapter-world manifest, District.tsx, collision.ts,
// or any runtime file, and it does NOT wire the metadata into the shipping app.
// This is the foundation the later runtime integration consumes.
//
// Run: node assets/pipeline/build_collision_manifest.mjs
globalThis.self = globalThis;
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { assemble, PATHS, round } from "./collision_lib.mjs";

const model = await assemble();

mkdirSync(PATHS.outDir, { recursive: true });

// ---- 1. Machine-readable manifest (JSON) -----------------------------------
const jsonPath = join(PATHS.outDir, "collision-manifest.json");
writeFileSync(jsonPath, JSON.stringify(model, null, 2) + "\n");

// ---- 2. Generated TS (typed, non-shipping; lives in assets/build) ----------
const tsPath = join(PATHS.outDir, "collision-manifest.generated.ts");
writeFileSync(tsPath, emitTs(model));

// ---- 3. Human-readable audit report (Markdown) -----------------------------
const reportPath = join(PATHS.outDir, "collision-report.md");
writeFileSync(reportPath, emitReport(model));

// ---- Console summary --------------------------------------------------------
const s = model.summary;
console.log("collision-manifest build complete");
console.log(`  assets scanned:        ${s.scanned} (${s.withGlb} with GLB)`);
console.log(`  profiled (colliders):  ${s.profiled}`);
console.log(`  explicit none:         ${s.explicitNone}`);
console.log(`  pending contracts:     ${s.pending}`);
console.log(`  referenced, no sidecar:${s.unprofiledReferenced}`);
console.log(`  errors / warnings:     ${s.errors} / ${s.warnings}`);
console.log(`  -> ${jsonPath}`);
console.log(`  -> ${tsPath}`);
console.log(`  -> ${reportPath}`);

function emitTs(model) {
  const header = `// GENERATED by assets/pipeline/build_collision_manifest.mjs — DO NOT EDIT.
// Asset-local collision metadata foundation. Not yet wired into the runtime;
// the later integration step imports COLLISION_METADATA from here (or the
// sibling JSON) and applies per-placement fit scale + yaw + world position.
// Coordinate frame: fit-normalized, asset-local, meters (centered XZ, grounded).

export type CollisionShape = "box" | "capsule" | "support" | "hazard" | "none";
export type ReservedShape = "door" | "traversal";

export interface BoxCollider {
  id: string; shape: "box";
  center: [number, number, number];
  half: [number, number, number];
  yaw?: number; tags?: string[]; marginReason?: string;
}
export interface CapsuleCollider {
  id: string; shape: "capsule";
  a: [number, number, number]; b: [number, number, number]; radius: number;
  tags?: string[]; marginReason?: string;
}
export interface SupportCollider {
  id: string; shape: "support";
  polygon: [number, number][]; y: number; link: string | string[];
  tags?: string[]; marginReason?: string;
}
export interface HazardCollider {
  id: string; shape: "hazard";
  polygon: [number, number][]; minY: number; maxY?: number; link: string | string[];
  tags?: string[]; marginReason?: string;
}
export type Collider = BoxCollider | CapsuleCollider | SupportCollider | HazardCollider;

export interface CollisionAsset {
  assetKey: string;
  category: string | null;
  profile: string | null;
  frontAxis: string | null;
  pendingDoorContract: boolean;
  pendingInteriorPlacement: boolean;
  fileExists: boolean;
  hash: string | null;
  rawSize: [number, number, number] | null;
  fittedSize: [number, number, number] | null;
  colliders: Collider[];
  note: string | null;
}

`;
  const entries = Object.values(model.assets).map((a) => {
    const obj = {
      assetKey: a.assetKey,
      category: a.category,
      profile: a.profile,
      frontAxis: a.frontAxis,
      pendingDoorContract: a.pendingDoorContract,
      pendingInteriorPlacement: a.pendingInteriorPlacement,
      fileExists: a.fileExists,
      hash: a.measured?.hash ?? null,
      rawSize: a.measured ? a.measured.rawSize.map((n) => round(n)) : null,
      fittedSize: a.derived?.fittedSize ?? null,
      colliders: a.colliders ?? [],
      note: a.note,
    };
    return `  ${JSON.stringify(a.assetKey)}: ${JSON.stringify(obj)}`;
  });
  return (
    header +
    `export const COLLISION_METADATA: Record<string, CollisionAsset> = {\n` +
    entries.join(",\n") +
    `\n};\n\nexport const COLLISION_GENERATED_AT = ${JSON.stringify(model.generatedAt)};\n`
  );
}

function emitReport(model) {
  const s = model.summary;
  const lines = [];
  lines.push("# Collision-metadata foundation report");
  lines.push("");
  lines.push(`Generated: ${model.generatedAt}`);
  lines.push("");
  lines.push("This report is produced by `build_collision_manifest.mjs`. It measures the");
  lines.push("deployed GLB set, cross-references authored collision sidecars, and exposes the");
  lines.push("nominal-slot vs measured-fitted-bounds deltas the Sol audit flagged, so the later");
  lines.push("runtime integration can remove invisible barriers without racing active work.");
  lines.push("");
  lines.push("## Coverage");
  lines.push("");
  lines.push(`- Assets scanned: **${s.scanned}** (${s.withGlb} with a deployed GLB)`);
  lines.push(`- Profiled (authored colliders): **${s.profiled}**`);
  lines.push(`- Explicit \`none\`: **${s.explicitNone}**`);
  lines.push(`- Pending contracts (door/interior): **${s.pending}**`);
  lines.push(`- Referenced but not yet profiled: **${s.unprofiledReferenced}**`);
  lines.push(`- Errors / warnings: **${s.errors} / ${s.warnings}**`);
  lines.push("");
  lines.push("### By category");
  lines.push("");
  for (const [k, v] of Object.entries(s.byCategory).sort()) lines.push(`- ${k}: ${v}`);
  lines.push("");
  lines.push("### By issue category");
  lines.push("");
  lines.push("| issue | errors | warnings |");
  lines.push("| --- | ---: | ---: |");
  for (const [k, v] of Object.entries(s.byIssueCategory).sort()) lines.push(`| ${k} | ${v.error} | ${v.warning} |`);
  lines.push("");

  // Building deltas: nominal slot vs measured fitted footprint.
  lines.push("## Building nominal-slot vs fitted-footprint deltas");
  lines.push("");
  lines.push("Large deltas = invisible barrier: the manifest slot is far wider than the model");
  lines.push("actually fills once min-axis fitted. The later integration should collide the");
  lines.push("fitted footprint (or the authored solid-body box), never the raw slot.");
  lines.push("");
  lines.push("| building | glb | nominal slot (x×z) | fitted footprint (x×z) | Δx | Δz |");
  lines.push("| --- | --- | --- | --- | ---: | ---: |");
  for (const a of Object.values(model.assets)) {
    for (const pl of a.derived?.placements ?? []) {
      if (pl.kind !== "building") continue;
      lines.push(
        `| ${pl.id} | ${a.assetKey} | ${pl.nominalSlot[0]}×${pl.nominalSlot[1]} | ${pl.fittedFootprint[0]}×${pl.fittedFootprint[1]} | ${pl.deltaX} | ${pl.deltaZ} |`,
      );
    }
  }
  lines.push("");

  // Prop recommended footprint vs existing collide tuple.
  lines.push("## Prop fitted footprint vs existing manifest collide tuple");
  lines.push("");
  lines.push("`Δ = fittedFootprint − collide`. Positive = the visible model is wider than the");
  lines.push("current collider (under-collided); negative = the collider is wider than the model");
  lines.push("(over-collided / phantom wall). Reported only — manifest is never edited here.");
  lines.push("");
  lines.push("| glb | pos | fitted footprint | collide tuple | Δx | Δz |");
  lines.push("| --- | --- | --- | --- | ---: | ---: |");
  for (const a of Object.values(model.assets)) {
    for (const pl of a.derived?.placements ?? []) {
      if (pl.kind !== "prop" || !pl.collide) continue;
      const d = pl.recommendedVsCollide;
      lines.push(
        `| ${a.assetKey} | ${pl.pos?.[0]},${pl.pos?.[2]} | ${pl.fittedFootprint[0]}×${pl.fittedFootprint[1]} | ${pl.collide[0]}×${pl.collide[1]} | ${d?.[0]} | ${d?.[1]} |`,
      );
    }
  }
  lines.push("");

  // Pending / still-blocked-on-active-worker categories.
  lines.push("## Pending on active-worker outputs");
  lines.push("");
  const pendingDoor = Object.values(model.assets).filter((a) => a.pendingDoorContract).map((a) => a.assetKey);
  const pendingInt = Object.values(model.assets).filter((a) => a.pendingInteriorPlacement).map((a) => a.assetKey);
  lines.push(`- **Door contract** (openings deferred): ${pendingDoor.join(", ") || "none"}`);
  lines.push(`- **Interior placement** (final profile deferred): ${pendingInt.join(", ") || "none"}`);
  lines.push("");

  // Full issue log.
  lines.push("## Issues");
  lines.push("");
  const errors = model.issues.filter((i) => i.severity === "error");
  const warnings = model.issues.filter((i) => i.severity === "warning");
  lines.push(`### Errors (${errors.length})`);
  lines.push("");
  for (const i of errors) lines.push(`- \`${i.category}\` **${i.assetKey}**: ${i.message}`);
  if (!errors.length) lines.push("- none");
  lines.push("");
  lines.push(`### Warnings (${warnings.length})`);
  lines.push("");
  for (const i of warnings) lines.push(`- \`${i.category}\` **${i.assetKey}**: ${i.message}`);
  if (!warnings.length) lines.push("- none");
  lines.push("");
  return lines.join("\n");
}
