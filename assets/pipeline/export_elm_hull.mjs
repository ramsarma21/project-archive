// Dump the collision M1 authored for the Liberty elm into a plain JSON hull the
// Blender build step can read.
//
// The build must not carry its own copy of the numbers. If the level moves a
// bough, this regenerates and the mesh is rebuilt against the new hull; nobody
// has to remember that a spec sheet in a Python file also needs editing.
//
// Run: node --import tsx assets/pipeline/export_elm_hull.mjs
import { writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const { GEOMETRY } = await import(
  pathToFileURL(join(repoRoot, "packages", "mission-m1", "src", "level", "geometry.ts"))
);
const { ASSETS } = await import(
  pathToFileURL(join(repoRoot, "packages", "mission-m1", "src", "assets.ts"))
);

const ASSET_KEY = "liberty-elm-hero";
const requirement = ASSETS.find((a) => a.key === ASSET_KEY);
const trunk = GEOMETRY.masses.find((m) => m.asset === ASSET_KEY);
const tiers = GEOMETRY.decks
  .filter((d) => d.asset === ASSET_KEY)
  .sort((a, b) => a.y - b.y);
if (!requirement || !trunk) throw new Error(`${ASSET_KEY} is not declared`);

// Everything is emitted relative to the bole axis, because that is the point
// the renderer will place the tree on.
const axisX = (trunk.rect.minX + trunk.rect.maxX) / 2;
const axisZ = (trunk.rect.minZ + trunk.rect.maxZ) / 2;

const hull = {
  key: ASSET_KEY,
  note: "generated by assets/pipeline/export_elm_hull.mjs; do not hand-edit",
  sizeM: requirement.sizeM,
  axisWorld: [axisX, axisZ],
  bole: {
    radius: trunk.round?.radius ?? (trunk.rect.maxX - trunk.rect.minX) / 2,
    baseY: trunk.baseY,
    topY: trunk.topY,
  },
  // Rects are game-space offsets from the bole axis: +x east, +z south.
  tiers: tiers.map((tier) => ({
    id: tier.id,
    y: tier.y,
    minX: tier.rect.minX - axisX,
    maxX: tier.rect.maxX - axisX,
    minZ: tier.rect.minZ - axisZ,
    maxZ: tier.rect.maxZ - axisZ,
    tags: tier.tags,
  })),
};

const out = resolve(repoRoot, "assets", "source", "collision", `${ASSET_KEY}.hull.json`);
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `${JSON.stringify(hull, null, 2)}\n`);
console.log("WROTE", out);
console.log(JSON.stringify(hull, null, 2));
