// Export the browser-safe subset of the collision build. The web runtime never
// parses GLBs or imports Node-only build metadata; it consumes this generated
// TypeScript module instead.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "../..");
const sourcePath = resolve(root, "assets/build/collision/collision-manifest.json");
const outputPath = resolve(
  root,
  "apps/web/src/world/collisionManifest.generated.ts",
);
const source = JSON.parse(readFileSync(sourcePath, "utf8"));

const runtimeAssets = Object.fromEntries(
  Object.values(source.assets)
    .filter(
      (asset) =>
        asset.fileExists &&
        asset.profile &&
        (asset.colliders.length > 0 || asset.profile === "none"),
    )
    .map((asset) => [
      asset.assetKey,
      {
        assetKey: asset.assetKey,
        category: asset.category,
        profile: asset.profile,
        pendingDoorContract: Boolean(asset.pendingDoorContract),
        pendingInteriorPlacement: Boolean(asset.pendingInteriorPlacement),
        rawSize: asset.measured?.rawSize ?? null,
        fittedSize: asset.derived?.fittedSize ?? null,
        colliders: asset.colliders,
      },
    ]),
);

const header = `// GENERATED by assets/pipeline/export_runtime_collision_manifest.mjs — DO NOT EDIT.
// Runtime-safe asset-local collision metadata. No GLB parsing occurs in browser.

export type RuntimeCollider =
  | { id: string; shape: "box"; center: [number, number, number]; half: [number, number, number]; yaw?: number; tags?: string[]; marginReason?: string }
  | { id: string; shape: "capsule"; a: [number, number, number]; b: [number, number, number]; radius: number; tags?: string[]; marginReason?: string }
  | { id: string; shape: "support"; polygon: [number, number][]; y: number; link: string | string[]; tags?: string[]; marginReason?: string }
  | { id: string; shape: "hazard"; polygon: [number, number][]; minY: number; maxY?: number; link: string | string[]; tags?: string[]; marginReason?: string };

export interface RuntimeCollisionAsset {
  assetKey: string;
  category: string | null;
  profile: string;
  pendingDoorContract: boolean;
  pendingInteriorPlacement: boolean;
  rawSize: [number, number, number] | null;
  fittedSize: [number, number, number] | null;
  colliders: RuntimeCollider[];
}

`;

writeFileSync(
  outputPath,
  `${header}export const RUNTIME_COLLISION_METADATA: Record<string, RuntimeCollisionAsset> = ${JSON.stringify(runtimeAssets, null, 2)};\n`,
);
console.log(
  `runtime collision manifest: ${Object.keys(runtimeAssets).length} assets -> ${outputPath}`,
);
